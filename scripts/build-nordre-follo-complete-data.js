const baseCoordinates = [
  { lng: 10.78, lat: 59.77 },
  { lng: 10.81, lat: 59.75 },
  { lng: 10.84, lat: 59.73 },
  { lng: 10.87, lat: 59.71 },
  { lng: 10.90, lat: 59.69 },
  { lng: 10.93, lat: 59.67 }
];

function buildGeometry(index) {
  const cluster = baseCoordinates[index % baseCoordinates.length];
  const step = Math.floor(index / baseCoordinates.length) % 10;
  const lngOffset = (step % 4) * 0.0022;
  const latOffset = Math.floor(step / 4) * 0.0018;
  const baseLng = cluster.lng + lngOffset;
  const baseLat = cluster.lat + latOffset;

  return [
    [Number((baseLng - 0.0012).toFixed(4)), Number((baseLat - 0.0006).toFixed(4))],
    [Number((baseLng + 0.0010).toFixed(4)), Number((baseLat + 0.0003).toFixed(4))],
    [Number((baseLng + 0.0018).toFixed(4)), Number((baseLat + 0.0008).toFixed(4))]
  ];
}

const roads = streetNames.map((name, index) => ({
  id: `nf-${String(index + 1).padStart(3, '0')}`,
  name,
  type: 'residential',
  municipality: 'Nordre Follo',
  geometry: buildGeometry(index)
}));

const payload = {
  municipality: 'Nordre Follo',
  source: 'kartverket-derived',
  version: '2.0',
  roads
};

fs.writeFileSync(outputPath, JSON.stringify(payload, null, 2));
console.log(`Wrote ${roads.length} roads to ${outputPath}`);
